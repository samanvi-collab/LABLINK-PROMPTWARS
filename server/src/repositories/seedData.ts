/**
 * Generates an ISO timestamp in IST (+05:30) relative to an anchor UTC day.
 */
function istTimestamp(baseUtcDayMs: number, dayOffset: number, hourIst: number, minuteIst = 0): string {
  // IST is UTC+05:30 (330 minutes)
  const istOffsetMs = 330 * 60_000;
  const targetMs =
    baseUtcDayMs +
    dayOffset * 86_400_000 +
    hourIst * 3_600_000 +
    minuteIst * 60_000 -
    istOffsetMs;
  return new Date(targetMs).toISOString();
}

/**
 * Finds the next weekday (Mon-Fri) offset >= minOffset from baseUtcDayMs in IST.
 */
function nextWeekdayOffset(baseUtcDayMs: number, minOffset: number): number {
  let offset = minOffset;
  while (true) {
    const sample = new Date(baseUtcDayMs + offset * 86_400_000 + 12 * 3_600_000);
    const day = sample.getUTCDay();
    if (day >= 1 && day <= 5) {
      return offset;
    }
    offset += 1;
  }
}

